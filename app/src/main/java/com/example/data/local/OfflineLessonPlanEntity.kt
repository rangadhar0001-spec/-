package com.example.data.local

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.example.domain.model.LessonPlan
import com.google.firebase.Timestamp
import java.util.Date

enum class SyncStatus {
    SYNCED,
    PENDING_CREATE,
    PENDING_UPDATE,
    PENDING_DELETE,
    SYNC_ERROR
}

@Entity(tableName = "offline_lesson_plans")
data class OfflineLessonPlanEntity(
    @PrimaryKey val id: String,
    val userId: String,
    val authorName: String,
    val title: String,
    val stage: String,
    val classLevel: String,
    val subject: String,
    val medium: String,
    val topic: String,
    val durationMinutes: Long,
    val planDay: Long,
    val planMonth: Long,
    val planYear: Long,
    val learningObjectives: String,
    val tlmMaterials: String,
    val teacherActivities: String,
    val studentActivities: String,
    val aditiStep: String,
    val aditiMinutes: Long,
    val bodhaStep: String,
    val bodhaMinutes: Long,
    val abhyasaStep: String,
    val abhyasaMinutes: Long,
    val prayogaStep: String,
    val prayogaMinutes: Long,
    val prasaraStep: String,
    val prasaraMinutes: Long,
    val competencyQuestions: String,
    val assessmentCriteria: String,
    val homeworkActivities: String,
    val inclusiveSuggestions: String,
    val summary: String,
    val teacherReflection: String,
    val isAiGenerated: Boolean,
    val isVerified: Boolean,
    val status: String,
    val createdAtMillis: Long,
    val updatedAtMillis: Long,
    val isDownloaded: Boolean = true,
    val syncStatus: String = SyncStatus.SYNCED.name,
    val lastModifiedLocalMillis: Long = System.currentTimeMillis(),
    val lastSyncedMillis: Long = 0L,
    val lastSyncError: String? = null
) {
    fun toDomain(): LessonPlan = LessonPlan(
        id = id,
        userId = userId,
        authorName = authorName,
        title = title,
        stage = stage,
        classLevel = classLevel,
        subject = subject,
        medium = medium,
        topic = topic,
        durationMinutes = durationMinutes,
        planDay = planDay,
        planMonth = planMonth,
        planYear = planYear,
        learningObjectives = learningObjectives,
        tlmMaterials = tlmMaterials,
        teacherActivities = teacherActivities,
        studentActivities = studentActivities,
        aditiStep = aditiStep,
        aditiMinutes = aditiMinutes,
        bodhaStep = bodhaStep,
        bodhaMinutes = bodhaMinutes,
        abhyasaStep = abhyasaStep,
        abhyasaMinutes = abhyasaMinutes,
        prayogaStep = prayogaStep,
        prayogaMinutes = prayogaMinutes,
        prasaraStep = prasaraStep,
        prasaraMinutes = prasaraMinutes,
        competencyQuestions = competencyQuestions,
        assessmentCriteria = assessmentCriteria,
        homeworkActivities = homeworkActivities,
        inclusiveSuggestions = inclusiveSuggestions,
        summary = summary,
        teacherReflection = teacherReflection,
        isAiGenerated = isAiGenerated,
        isVerified = isVerified,
        status = status,
        createdAt = if (createdAtMillis > 0L) Timestamp(Date(createdAtMillis)) else null,
        updatedAt = if (updatedAtMillis > 0L) Timestamp(Date(updatedAtMillis)) else null
    )
}

fun LessonPlan.toOfflineEntity(
    isDownloaded: Boolean = true,
    syncStatus: SyncStatus = SyncStatus.SYNCED,
    lastModifiedLocalMillis: Long = System.currentTimeMillis(),
    lastSyncedMillis: Long = if (syncStatus == SyncStatus.SYNCED) System.currentTimeMillis() else 0L,
    lastSyncError: String? = null
): OfflineLessonPlanEntity {
    val now = System.currentTimeMillis()
    return OfflineLessonPlanEntity(
        id = id,
        userId = userId,
        authorName = authorName,
        title = title,
        stage = stage,
        classLevel = classLevel,
        subject = subject,
        medium = medium,
        topic = topic,
        durationMinutes = durationMinutes,
        planDay = planDay,
        planMonth = planMonth,
        planYear = planYear,
        learningObjectives = learningObjectives,
        tlmMaterials = tlmMaterials,
        teacherActivities = teacherActivities,
        studentActivities = studentActivities,
        aditiStep = aditiStep,
        aditiMinutes = aditiMinutes,
        bodhaStep = bodhaStep,
        bodhaMinutes = bodhaMinutes,
        abhyasaStep = abhyasaStep,
        abhyasaMinutes = abhyasaMinutes,
        prayogaStep = prayogaStep,
        prayogaMinutes = prayogaMinutes,
        prasaraStep = prasaraStep,
        prasaraMinutes = prasaraMinutes,
        competencyQuestions = competencyQuestions,
        assessmentCriteria = assessmentCriteria,
        homeworkActivities = homeworkActivities,
        inclusiveSuggestions = inclusiveSuggestions,
        summary = summary,
        teacherReflection = teacherReflection,
        isAiGenerated = isAiGenerated,
        isVerified = isVerified,
        status = status,
        createdAtMillis = createdAt?.toDate()?.time ?: now,
        updatedAtMillis = updatedAt?.toDate()?.time ?: now,
        isDownloaded = isDownloaded,
        syncStatus = syncStatus.name,
        lastModifiedLocalMillis = lastModifiedLocalMillis,
        lastSyncedMillis = lastSyncedMillis,
        lastSyncError = lastSyncError
    )
}
